/**
 * Высоты расчётных стен для подбора стеновых прогонов.
 *
 * Правило из рабочей тетради расчётчика (заголовок «Калькулятор
 * ограждайки»):
 *
 *   Торец: половина пролёта × 0,25 (15°) | × 0,1 (6°)
 *          + высота до карниза + 0,5 (+1,3)
 *   Вдоль: высота до карниза + 0,5 (+1,3)
 *
 * Два момента, которые легко испортить «улучшением»:
 *
 * 1. **0,25 и 0,1 — это НЕ тангенсы уклона.** tg(15°) = 0,2679 и
 *    tg(6°) = 0,1051; расчётчик пользуется округлёнными числами. На 21604
 *    (пролёт 18, карниз 7) правило даёт торец ровно 9,75 м — столько и
 *    стоит в его расчёте, а через тангенс вышло бы 9,91.
 * 2. **Добавка 0,5 м идёт на ОБЕ стены** и это та же добавка, что стоит в
 *    формуле площади обшивки в ведомости: `(C10 + 0,5)`. В тетради рядом
 *    в скобках указан вариант +1,3 — когда он применяется, пока не
 *    выяснено, поэтому это отдельный вход, а не зашитое число.
 *
 * Сверка по трём объектам (карниз — из шапки ведомости, факт — из копий
 * калькулятора, сохранённых расчётчиком):
 *
 * | Объект | Пролёт | Карниз | Торец: правило/факт | Вдоль: правило/факт |
 * |---|---|---|---|---|
 * | 21604 | 18 | 7,0 | 9,75 / 9,75 | 7,50 / 7,50 |
 * | 21876 | 12 | 4,5 | 6,50 / 6,50 | 5,00 / 4,80 |
 * | 22317 | 12 | 6,3 | 7,40 / 7,40 | 6,80 / 6,80 |
 *
 * Пять высот из шести совпадают в ноль. Расхождение 0,2 м на продольной
 * стене 21876 на результат не влияет: и 4,8, и 5,0 дают те же 4 ряда,
 * те же 720 п.м. профиля и те же 90 кг кронштейнов, что в ведомости.
 */

/** Добавка к высоте карниза по умолчанию, м. В тетради — 0,5 (+1,3). */
export const DEFAULT_WALL_HEIGHT_ALLOWANCE_m = 0.5;

/**
 * Множитель половины пролёта на подъём кровли: 0,25 при уклоне 15° и 0,1
 * при 6°. Промежуточные уклоны расчётчиком не описаны, поэтому берётся
 * ближайший из двух, а не интерполяция.
 */
export function ridgeRiseFactor(roofSlopeDeg: number): number {
  return Math.abs(roofSlopeDeg - 6) < Math.abs(roofSlopeDeg - 15) ? 0.1 : 0.25;
}

export interface WallHeightsInput {
  span_m: number;
  /** Высота до карниза — то, что стоит в шапке ведомости. */
  eaveHeight_m: number;
  roofSlopeDeg: number;
  /** Добавка к высоте карниза, м; по умолчанию 0,5. */
  allowance_m?: number;
}

export interface WallHeights {
  /** Торцевая стена, м — она же «высота здания» в Лист1!B8 подборщика. */
  gable_m: number;
  /** Продольная стена, м. */
  longitudinal_m: number;
}

export function wallPurlinHeights(input: WallHeightsInput): WallHeights {
  const allowance = input.allowance_m ?? DEFAULT_WALL_HEIGHT_ALLOWANCE_m;
  const longitudinal_m = input.eaveHeight_m + allowance;
  return {
    longitudinal_m,
    gable_m: (input.span_m / 2) * ridgeRiseFactor(input.roofSlopeDeg) + longitudinal_m,
  };
}
