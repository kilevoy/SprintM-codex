/**
 * Допущение, на котором построен расчёт: точной строки для этого города
 * в исходных таблицах ИНСИ нет, взята ближайшая.
 *
 * Так велел поступать проектировщик (вопрос 04 из списка расчётчику):
 * «считать по ближайшей строке с пометкой „требует проверки“». Раньше
 * такой город просто упирался в ошибку и менеджер не получал ничего.
 *
 * Из 1096 городов справочника это касается 47:
 *   13 — снеговая нагрузка выше последней ступени лестницы порогов,
 *   31 — сочетание снега с ветром в банке сечений не просчитано,
 *    3 — ветровой район не проставлен (пограничная зона).
 */
export interface ClimateApproximation {
  /**
   * Какая часть расчёта построена на допущении. Первые три — исходные
   * климатические; «высота» — высота вне банка сечений (капнута под предел,
   * сечение колонны нужно проверять вручную); «обшивка» — профлист вместо
   * сэндвич-панели, формула площади не сверена на реальном объекте.
   */
  kind: "ветер" | "лестница" | "сочетание" | "высота" | "обшивка" | "ограждение";
  /** Что именно взяли вместо точного значения — строкой для UI и печати. */
  message: string;
}
